export interface Plant {
  id: number;
  nameRu: string;
  nameLat: string;
  category: PlantCategory;
  type: PlantType;
  zones: number[];       // USDA hardiness zones
  bloomMonths: number[]; // 1-12
  bloomColor: string;
  heightMin: number;     // cm
  heightMax: number;     // cm
  widthMin: number;      // cm
  widthMax: number;      // cm
  light: LightReq;
  water: WaterReq;
  soil: string;
  careLevel: CareLevel;
  description: string;
  companions: number[];  // plant IDs — good neighbors
  enemies: number[];     // plant IDs — bad neighbors
  careCalendar: CareMonth[];
  imageUrl?: string;
}

export type PlantCategory =
  | 'fruit_tree'
  | 'decorative_tree'
  | 'shrub'
  | 'perennial'
  | 'annual'
  | 'rose'
  | 'grass'
  | 'vegetable'
  | 'conifer'
  | 'climber';

export type PlantType = 'tree' | 'shrub' | 'flower' | 'grass' | 'vegetable' | 'climber';

export type LightReq = 'full_sun' | 'partial_shade' | 'shade';
export type WaterReq = 'low' | 'medium' | 'high';
export type CareLevel = 'low' | 'medium' | 'high';

export interface CareMonth {
  month: number; // 1-12
  tasks: string[];
}

