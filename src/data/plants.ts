export function filterPlantsByZone(zone: number): Plant[] {
  return PLANTS.filter((p) => p.zones.includes(zone));
}

export function filterPlantsByCategory(category: PlantCategory): Plant[] {
  return PLANTS.filter((p) => p.category === category);
}

export function getContinuousBloom(
  zone: number,
  fromMonth: number = 4,
  toMonth: number = 10
): Plant[] {
  const eligible = filterPlantsByZone(zone).filter(
    (p) => p.bloomMonths.length > 0
  );
  const monthCoverage = new Set<number>();
  const selected: Plant[] = [];

  for (let m = fromMonth; m <= toMonth; m++) {
    if (!monthCoverage.has(m)) {
      const candidates = eligible.filter(
        (p) => p.bloomMonths.includes(m) && !selected.includes(p)
      );
      if (candidates.length > 0) {
        const best = candidates.reduce((a, b) =>
          b.bloomMonths.length > a.bloomMonths.length ? b : a
        );
        selected.push(best);
        best.bloomMonths.forEach((bm) => monthCoverage.add(bm));
      }
    }
  }

  return selected;
}

export function checkCompatibility(
  plantIds: number[]
): { good: [number, number][]; bad: [number, number][] } {
  const good: [number, number][] = [];
  const bad: [number, number][] = [];

  for (let i = 0; i < plantIds.length; i++) {
    for (let j = i + 1; j < plantIds.length; j++) {
      const a = PLANTS.find((p) => p.id === plantIds[i]);
      const b = PLANTS.find((p) => p.id === plantIds[j]);
      if (!a || !b) continue;

      if (a.companions.includes(b.id) || b.companions.includes(a.id)) {
        good.push([a.id, b.id]);
      }
      if (a.enemies.includes(b.id) || b.enemies.includes(a.id)) {
        bad.push([a.id, b.id]);
      }
    }
  }

  return { good, bad };
}
